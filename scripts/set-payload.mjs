#!/usr/bin/env node
/**
 * set-payload.mjs <id>
 *
 * Selects which game client gets packaged, by rewriting:
 *   game.lock.json            download URL, filename, expected sha256
 *   src-tauri/tauri.conf.json productName, mainBinaryName, identifier
 *
 * Each payload ships under its own bundle identifier so the apps install
 * side by side and keep separate world storage.
 *
 * Usage:
 *   node scripts/set-payload.mjs jm
 *   node scripts/set-payload.mjs gaius
 *   PAYLOAD=gaius node scripts/set-payload.mjs
 *   GAME_URL=https://example.com/client.html node scripts/set-payload.mjs custom
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PAYLOADS_FILE = resolve(ROOT, 'payloads.json');
const LOCK_FILE = resolve(ROOT, 'game.lock.json');
const CONF_FILE = resolve(ROOT, 'src-tauri/tauri.conf.json');

const log = (...a) => console.log('[set-payload]', ...a);

function die(msg) {
  console.error('\n[set-payload] FAILED\n');
  console.error(msg);
  console.error('');
  process.exit(1);
}

function readJson(p) {
  if (!existsSync(p)) die(`missing file: ${p}`);
  try {
    return JSON.parse(readFileSync(p, 'utf8'));
  } catch (e) {
    die(`${p} is not valid JSON: ${e.message}`);
  }
}

function writeJson(p, obj) {
  writeFileSync(p, JSON.stringify(obj, null, 2) + '\n', 'utf8');
}

const catalog = readJson(PAYLOADS_FILE);
const ids = Object.keys(catalog.payloads || {});
if (!ids.length) die('payloads.json defines no payloads');

const id = (process.argv[2] || process.env.PAYLOAD || catalog.default || '').trim();
if (!id) die(`no payload given.\n\nAvailable: ${ids.join(', ')}`);

const p = catalog.payloads[id];
if (!p) die(`unknown payload "${id}".\n\nAvailable: ${ids.join(', ')}`);

// ---------------------------------------------------------------- resolve URL
const envUrl = (process.env.GAME_URL || '').trim();
const url = envUrl || (p.url || '').trim();

if (!url) {
  die(
    `payload "${id}" has no URL.\n\n` +
      (id === 'custom'
        ? 'The "custom" payload reads the GAME_URL environment variable.\n' +
          'In CI set a repository variable named GAME_URL\n' +
          '(Settings > Secrets and variables > Actions > Variables).'
        : `Add a "url" to payloads.json > payloads > ${id}.`)
  );
}
try {
  const u = new URL(url);
  if (!/^https?:$/.test(u.protocol)) die(`payload URL must be http(s): ${url}`);
} catch {
  die(`payload URL is not a valid URL: ${url}`);
}

// A pinned checksum only applies to the pinned URL.
const sha256 = envUrl && envUrl !== p.url ? '' : (p.sha256 || '').trim().toLowerCase();
if (sha256 && !/^[0-9a-f]{64}$/.test(sha256)) {
  die(`payload "${id}" has a malformed sha256: ${p.sha256}`);
}

// ------------------------------------------------------------- game.lock.json
writeJson(LOCK_FILE, {
  comment: [
    'GENERATED by scripts/set-payload.mjs - do not hand-edit.',
    'Change payloads.json instead, then re-run: node scripts/set-payload.mjs <id>',
  ],
  payload: id,
  name: p.label || id,
  description: p.description || '',
  multiplayer: p.multiplayer || '',
  project: p.project || '',
  filename: p.filename || `${id}.html`,
  url,
  size: p.size || 0,
  sha256,
});

// -------------------------------------------------------- tauri.conf.json ids
const app = p.app || {};
for (const k of ['productName', 'mainBinaryName', 'identifier']) {
  if (!app[k]) die(`payloads.json > payloads > ${id} > app.${k} is missing`);
}
if (!/^[A-Za-z0-9.-]+$/.test(app.identifier)) {
  die(`identifier must be reverse-DNS (letters, digits, dots, hyphens): ${app.identifier}`);
}

const conf = readJson(CONF_FILE);
conf.productName = app.productName;
conf.mainBinaryName = app.mainBinaryName;
conf.identifier = app.identifier;
if (conf.app?.windows?.[0]) conf.app.windows[0].title = app.productName;
writeJson(CONF_FILE, conf);

// ------------------------------------------------------------------- report
log(`payload   ${id}  (${p.label || id})`);
log(`app       ${app.productName}  [${app.identifier}]`);
log(`url       ${url}`);
log(`sha256    ${sha256 || '(unpinned - the build will print the hash it sees)'}`);
if (p.multiplayer) log(`servers   ${p.multiplayer}`);
